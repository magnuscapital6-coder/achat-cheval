const DICTS = { fr, de, sl, en, da, nl }

interface LocaleValue {
  market: Market
  t: (key: TKey, vars?: Record<string, string | number>) => string
}

const LocaleContext = createContext<LocaleValue | null>(null)

/** Le marché se déduit de l'URL, une fois, au chargement de l'app. */
export const currentMarket = marketFromPath(typeof window === 'undefined' ? '/' : window.location.pathname)

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match))
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const value = useMemo<LocaleValue>(
    () => ({
      market: currentMarket,
      t: (key, vars) => interpolate(DICTS[currentMarket.lang][key] ?? fr[key] ?? key, vars),
    }),
    [],
  )

  // Les montants sont formatés comme dans la langue du marché.
  setMoneyLocale(currentMarket.lang)

  useEffect(() => {
    document.documentElement.lang = currentMarket.lang
  }, [])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useI18n() {
  const context = useContext(LocaleContext)
  if (!context) throw new Error('useI18n doit être utilisé dans <LocaleProvider>')
  return context
}

export function useT() {
  return useI18n().t
}

/** Clé de traduction d'une catégorie du catalogue. */
export const categoryKey = (category: string): TKey =>
  category === 'poneys' ? 'cat.poneys' : category === 'autres' ? 'cat.autres' : 'cat.chevaux'

export const categoryBlurbKey = (category: string): TKey =>
  category === 'poneys' ? 'cat.poneys.blurb' : category === 'autres' ? 'cat.autres.blurb' : 'cat.chevaux.blurb'
